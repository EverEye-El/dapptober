const ROWS = 5

export function renderAscii(word: string): string {
  const glyphs = word.toUpperCase().split("").map((char) => GLYPHS[char] ?? GLYPHS[" "])
  const lines: string[] = []
  for (let row = 0; row < ROWS; row += 1) {
    lines.push(glyphs.map((glyph) => glyph[row]).join(" "))
  }
  return lines.join("\n")
}

